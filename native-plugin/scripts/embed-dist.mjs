#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '../..');
const distDir = path.join(repoRoot, 'dist');
const outHeader = path.join(repoRoot, 'native-plugin/Source/EmbeddedWebAssets.h');

if (!fs.existsSync(distDir)) {
  console.error(`Error: dist directory not found at ${distDir}. Run 'npm run build' first.`);
  process.exit(1);
}

const MIME_TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'application/javascript; charset=utf-8',
  '.mjs': 'application/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.webp': 'image/webp',
  '.json': 'application/json; charset=utf-8',
  '.woff2': 'font/woff2',
  '.woff': 'font/woff',
  '.wasm': 'application/wasm',
  '.txt': 'text/plain; charset=utf-8',
};

function walkDir(dir) {
  const files = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue;
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...walkDir(fullPath));
    } else if (entry.isFile()) {
      files.push(fullPath);
    }
  }
  return files;
}

const files = walkDir(distDir).sort();
let out = `// Auto-generated by native-plugin/scripts/embed-dist.mjs - do not edit manually\n#pragma once\n\n#include <cstddef>\n#include <juce_core/juce_core.h>\n\nnamespace instajammable_assets {\n\nstruct EmbeddedAsset {\n  const char* path;\n  const unsigned char* data;\n  std::size_t size;\n  const char* mimeType;\n};\n\n`;

const entries = [];
files.forEach((filePath, idx) => {
  const relPath = '/' + path.relative(distDir, filePath).split(path.sep).join('/');
  const ext = path.extname(filePath).toLowerCase();
  const mimeType = MIME_TYPES[ext] || 'application/octet-stream';
  const buf = fs.readFileSync(filePath);
  const varName = `asset_data_${idx}`;
  const hexLines = [];
  for (let i = 0; i < buf.length; i += 24) {
    const slice = buf.subarray(i, i + 24);
    hexLines.push('  ' + Array.from(slice, b => `0x${b.toString(16).padStart(2, '0')}`).join(', '));
  }
  out += `inline const unsigned char ${varName}[] = {\n${hexLines.join(',\n')}\n};\n\n`;
  entries.push({ relPath, varName, size: buf.length, mimeType });
});

out += `inline constexpr EmbeddedAsset kAssets[] = {\n`;
for (const e of entries) {
  out += `  { ${JSON.stringify(e.relPath)}, ${e.varName}, ${e.size}u, ${JSON.stringify(e.mimeType)} },\n`;
}
out += `};\n\n`;

out += `inline const EmbeddedAsset* findEmbeddedAsset(const juce::String& rawPath) {\n`;
out += `  auto cleanPath = rawPath.upToFirstOccurrenceOf("?", false, false).upToFirstOccurrenceOf("#", false, false);\n`;
out += `  if (cleanPath.isEmpty() || cleanPath == "/") cleanPath = "/index.html";\n`;
out += `  if (!cleanPath.startsWithChar('/')) cleanPath = "/" + cleanPath;\n`;
out += `  for (const auto& asset : kAssets) {\n`;
out += `    if (cleanPath == asset.path) return &asset;\n`;
out += `  }\n`;
out += `  return nullptr;\n`;
out += `}\n\n`;
out += `} // namespace instajammable_assets\n`;

fs.mkdirSync(path.dirname(outHeader), { recursive: true });
fs.writeFileSync(outHeader, out, 'utf8');
console.log(`Embedded ${entries.length} files (${(out.length / 1024 / 1024).toFixed(2)} MB header) into ${path.relative(repoRoot, outHeader)}`);
